type Nested = { [key: string]: string | Nested };

function flatten(
  input: Nested,
  prefix = '',
  out: Record<string, string> = {}
): Record<string, string> {
  for (const key of Object.keys(input)) {
    const value = input[key];
    const path = prefix ? `${prefix}.${key}` : key;
    if (typeof value === 'object' && value !== null) {
      flatten(value as Nested, path, out);
    } else {
      out[path] = value as string;
    }
  }
  return out;
}

const EN_FLAT = flatten(en as unknown as Nested);
const UR_FLAT = flatten(ur as unknown as Nested);

export function translate(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>
): string {
  let str = (lang === 'ur' ? UR_FLAT[key] : undefined) ?? EN_FLAT[key] ?? key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      str = str.replaceAll(`{${k}}`, String(vars[k]));
    }
  }
  return str;
}

